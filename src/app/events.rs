#[derive(Debug, Clone)]
pub enum UserEvent {
    Navigate(String),
    SwitchTab { id: usize, url: String },
    ResetWorkspace { active_id: usize, active_url: String },
    RevealPendingTab { id: usize, gen: u64 },
    TabPaintReady(usize),
    ToggleBackgroundPlay { id: usize, active: bool },
    ToggleTabMute { id: usize, muted: bool },
    BootSync(usize),
    SyncNavState(usize),
    SyncConfig,
    SyncTabs,
    PageFinished { tab_id: usize, url: String },
    Toast(String),
    ToggleFullscreen(Option<bool>),
    ApplyZoom(f64),
    ClearSiteData,
    SyncAdblockFilters,
    UpdateUserAgent(Option<String>),
    WindowMinimize,
    WindowMaximize,
    WindowClose,
    WindowDrag,
    GoBack,
    GoForward,
    Reload,
    ReloadTab(usize),
    OpenDevtools,
    EvalScript(String),
    TrimWorkingSet,
}
