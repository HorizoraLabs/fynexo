#[derive(Debug, Clone)]
pub enum UserEvent {
    Navigate(String),
    SwitchTab { id: usize, url: String },
    ToggleBackgroundPlay { id: usize, active: bool },
    ToggleTabMute { id: usize, muted: bool },
    BootSync,
    SyncConfig,
    SyncTabs,
    RestoreScroll(f64),
    Toast(String),
    ToggleFullscreen(Option<bool>),
    ApplyZoom(f64),
    ClearSiteData,
    SyncAdblockFilters,
    UpdateUserAgent(Option<String>),
    WindowMinimize,
    WindowMaximize,
    WindowClose,
    WindowDrag,
    GoBack,
    GoForward,
    Reload,
    EvalScript(String),
    TrimWorkingSet,
}
